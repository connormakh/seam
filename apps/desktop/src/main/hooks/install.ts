import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * `seam-hook`: what Claude Code runs on every hook event Seam asks for.
 *
 * It does one thing, like the MCP server: forward the event JSON on stdin to
 * the control socket, print whatever context comes back, exit 0. Every
 * decision stays in the app. It is deliberately incapable of failing loudly,
 * because a hook that errors or hangs stalls the user's turn: no socket, no
 * answer, a bad reply, all of them mean print nothing and exit 0.
 *
 * It is installed rather than bundled because Claude spawns it. The wrapper
 * exists because Electron's binary only behaves as node with
 * ELECTRON_RUN_AS_NODE set, and a hook entry has nowhere to put an env var.
 */
const HOOK = `#!/usr/bin/env node
// Generated by Seam. Edits are overwritten on launch.
import { connect } from 'node:net'

const SOCKET = process.env.SEAM_SOCKET
const TOKEN = process.env.SEAM_SESSION_TOKEN
// Shorter than the hook timeout, so Seam is never the reason a turn stalls.
const DEADLINE_MS = 3000

function quit() {
  process.exit(0)
}

let input = ''
process.stdin.setEncoding('utf8')
process.stdin.on('data', (c) => {
  input += c
})
process.stdin.on('end', () => {
  if (!SOCKET || !TOKEN) return quit()
  let event
  try {
    event = JSON.parse(input)
  } catch {
    return quit()
  }

  const socket = connect(SOCKET)
  const timer = setTimeout(quit, DEADLINE_MS)
  let buffer = ''
  socket.setEncoding('utf8')
  socket.on('error', quit)
  socket.on('close', quit)
  socket.on('connect', () => {
    socket.write(JSON.stringify({ id: 1, token: TOKEN, method: 'hook', params: { event } }) + '\\n')
  })
  socket.on('data', (chunk) => {
    buffer += chunk
    const cut = buffer.indexOf('\\n')
    if (cut === -1) return
    clearTimeout(timer)
    socket.destroy()
    try {
      const reply = JSON.parse(buffer.slice(0, cut))
      const context = reply && reply.ok && reply.result && reply.result.additionalContext
      if (context) {
        process.stdout.write(
          JSON.stringify({
            hookSpecificOutput: {
              hookEventName: event.hook_event_name,
              additionalContext: context
            }
          }) + '\\n'
        )
      }
    } catch {
      // A reply we cannot read is the same as no reply.
    }
    quit()
  })
})
`

/** Wrap the script so it runs under Electron's node, whatever the PATH holds. */
const wrapper = (nodePath: string, scriptPath: string): string =>
  `#!/bin/sh
# Generated by Seam. ELECTRON_RUN_AS_NODE makes Electron behave as node, which
# a hook entry has no env field to set.
exec env ELECTRON_RUN_AS_NODE=1 ${JSON.stringify(nodePath)} ${JSON.stringify(scriptPath)} "$@"
`

/** Write the hook and its wrapper. Returns the path Claude should run. */
export function installHook(dir: string, nodePath: string): string {
  mkdirSync(dir, { recursive: true, mode: 0o700 })
  const script = join(dir, 'seam-hook.mjs')
  writeFileSync(script, HOOK, { mode: 0o700 })
  const entry = join(dir, 'seam-hook')
  writeFileSync(entry, wrapper(nodePath, script), { mode: 0o700 })
  return entry
}

/**
 * The --settings file for one session. Per session because it is the session
 * token in the environment that tells Seam who is calling, and because
 * Claude Code merges hook entries from every settings source: the user's own
 * hooks keep running alongside these.
 *
 * Both events are synchronous. They are the two that can return context, and
 * an async hook's output is never read.
 */
export function writeHookSettings(o: { dir: string; sessionId: string; hookPath: string }): string {
  mkdirSync(o.dir, { recursive: true, mode: 0o700 })
  const file = join(o.dir, `${o.sessionId}.hooks.json`)
  // Claude Code runs a hook command through a shell, and this path lives
  // under "Application Support", so unquoted it is two words and neither
  // exists. Single quotes, with any quote in the path closed and reopened.
  const command = `'${o.hookPath.replace(/'/g, `'\\''`)}'`
  const blocking = { type: 'command', command, timeout: 5, async: false }
  // Status events return nothing, so they need not hold up the turn.
  const watching = { type: 'command', command, timeout: 5, async: true }
  const settings = {
    hooks: {
      // The start of a turn: what the user attached, and everything the shell
      // did since Claude last heard.
      // What the session can reach, said once at the start so Claude need
      // not go looking before its first command.
      SessionStart: [{ hooks: [blocking] }],
      UserPromptSubmit: [{ hooks: [blocking] }],
      // And again between tool calls, so a failure that happens while Claude
      // is working reaches it before the turn ends.
      PostToolUse: [{ hooks: [blocking] }],
      // The rest is Seam watching: whether a session is working, waiting on
      // an answer, or done, so a tab that is not in front can say so.
      Notification: [{ hooks: [watching] }],
      PermissionRequest: [{ hooks: [watching] }],
      Stop: [{ hooks: [watching] }],
      SessionEnd: [{ hooks: [watching] }]
    }
  }
  writeFileSync(file, `${JSON.stringify(settings, null, 2)}\n`, { mode: 0o600 })
  return file
}
