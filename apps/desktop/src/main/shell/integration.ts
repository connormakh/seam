import { mkdirSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

/**
 * Shell integration: Seam shells report each command as it starts and ends.
 *
 * Every report is one line appended to the file in $SEAM_EVENTS:
 *
 *   S <tab> <line> <tab> <cwd> <tab> <command>     command started
 *   E <tab> <line> <tab> <exit code>                command finished
 *
 * <line> is an absolute line in the pane's tmux history (history_size +
 * cursor_y), so the output of a command is the lines from its S line up to,
 * not including, its E line. Text fields escape \\, tab, newline and CR.
 *
 * Appending uses shell builtins only; the one extra process per report is
 * a tmux client asking where the cursor is. Users' own startup files are
 * loaded first and left untouched.
 */

/** zsh: everything goes through ZDOTDIR, so Seam points it at its own files, which load the user's. */
const ZSHENV = `# Generated by Seam. Loads your ~/.zshenv, then keeps Seam's ZDOTDIR for the remaining startup files.
__seam_zdotdir="$ZDOTDIR"
ZDOTDIR="\${SEAM_USER_ZDOTDIR:-$HOME}"
[[ -f "$ZDOTDIR/.zshenv" ]] && source "$ZDOTDIR/.zshenv"
SEAM_USER_ZDOTDIR="$ZDOTDIR"
ZDOTDIR="$__seam_zdotdir"
unset __seam_zdotdir
`

const ZPROFILE = `# Generated by Seam. Loads your .zprofile.
__seam_zdotdir="$ZDOTDIR"
ZDOTDIR="$SEAM_USER_ZDOTDIR"
[[ -f "$ZDOTDIR/.zprofile" ]] && source "$ZDOTDIR/.zprofile"
ZDOTDIR="$__seam_zdotdir"
unset __seam_zdotdir
`

/** After .zshrc, ZDOTDIR goes back to the user's, so zsh reads their .zlogin itself. */
const ZSHRC = `# Generated by Seam. Loads your .zshrc, then Seam's shell integration.
__seam_dir="$ZDOTDIR"
ZDOTDIR="$SEAM_USER_ZDOTDIR"
[[ -f "$ZDOTDIR/.zshrc" ]] && source "$ZDOTDIR/.zshrc"
source "$__seam_dir/seam-integration.zsh"
unset __seam_dir
`

const ZSH_INTEGRATION = `# Generated by Seam: report commands to Seam. Does nothing outside Seam.
[[ -n "$SEAM_EVENTS" && -n "$TMUX" && -n "$TMUX_PANE" && -o interactive ]] || return 0
[[ -n "$__seam_loaded" ]] && return 0
typeset -g __seam_loaded=1 __seam_running=0

# Escape into REPLY (no subshell).
__seam_esc() {
  REPLY=\${1//\\\\/\\\\\\\\}
  REPLY=\${REPLY//$'\\t'/\\\\t}
  REPLY=\${REPLY//$'\\n'/\\\\n}
  REPLY=\${REPLY//$'\\r'/\\\\r}
}

# Absolute line of the cursor in tmux history, into REPLY.
__seam_line() {
  local pos
  pos=$("\${SEAM_TMUX_BIN:-tmux}" display-message -p -t "$TMUX_PANE" '#{e|+:#{history_size},#{cursor_y}}' 2>/dev/null)
  REPLY=\${pos:--1}
}

__seam_preexec() {
  local line cwd
  __seam_line; line=$REPLY
  __seam_esc "$PWD"; cwd=$REPLY
  __seam_esc "$1"
  print -r -- "S"$'\\t'"$line"$'\\t'"$cwd"$'\\t'"$REPLY" >>| "$SEAM_EVENTS" 2>/dev/null
  __seam_running=1
}

__seam_precmd() {
  local code=$?
  (( __seam_running )) || return 0
  __seam_running=0
  __seam_line
  print -r -- "E"$'\\t'"$REPLY"$'\\t'"$code" >>| "$SEAM_EVENTS" 2>/dev/null
}

autoload -Uz add-zsh-hook
add-zsh-hook preexec __seam_preexec
# First in line, so it sees the command's exit status before other hooks run.
precmd_functions=(__seam_precmd \${precmd_functions[@]:#__seam_precmd})
`

/**
 * bash: started with --init-file instead of as a login shell, so the file
 * first does what a login shell would (profile files), then integrates.
 */
const BASH_INIT = `# Generated by Seam. Loads your login files, then Seam's shell integration.
[[ -r /etc/profile ]] && source /etc/profile
for __seam_f in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
  if [[ -r "$__seam_f" ]]; then source "$__seam_f"; break; fi
done
unset __seam_f
source "\${BASH_SOURCE[0]%/*}/seam-integration.bash"
`

const BASH_INTEGRATION = `# Generated by Seam: report commands to Seam. Does nothing outside Seam.
[[ -n "$SEAM_EVENTS" && -n "$TMUX" && -n "$TMUX_PANE" && $- == *i* ]] || return 0
[[ -n "$__seam_loaded" ]] && return 0
__seam_loaded=1
__seam_armed=0
__seam_running=0

__seam_esc() {
  REPLY=\${1//\\\\/\\\\\\\\}
  REPLY=\${REPLY//$'\\t'/\\\\t}
  REPLY=\${REPLY//$'\\n'/\\\\n}
  REPLY=\${REPLY//$'\\r'/\\\\r}
}

__seam_line() {
  local pos
  pos=$("\${SEAM_TMUX_BIN:-tmux}" display-message -p -t "$TMUX_PANE" '#{e|+:#{history_size},#{cursor_y}}' 2>/dev/null)
  REPLY=\${pos:--1}
}

# The S report. On bash 4.4+ it runs from PS0, which bash expands after
# reading a command line and before running it (subshells included); the
# $(...) there is a subshell, so it only writes the report.
__seam_start() {
  local line cwd cmd
  cmd=$(HISTTIMEFORMAT= builtin history 1)
  cmd=\${cmd#*[0-9]  }
  [[ -n $cmd ]] || cmd=$1
  __seam_line; line=$REPLY
  __seam_esc "$PWD"; cwd=$REPLY
  __seam_esc "$cmd"
  printf 'S\\t%s\\t%s\\t%s\\n' "$line" "$cwd" "$REPLY" >> "$SEAM_EVENTS" 2>/dev/null
}

if (( BASH_VERSINFO[0] > 4 || (BASH_VERSINFO[0] == 4 && BASH_VERSINFO[1] >= 4) )); then
  # The subscript is arithmetic evaluated in this shell, not the subshell:
  # it is how PS0 tells precmd that a command ran. An empty line runs nothing.
  PS0='$(__seam_start)\${__seam_ps0[__seam_running=1]}'"$PS0"
  __seam_debug() { :; }
else
  # Older bash (macOS ships 3.2) has no PS0: use the DEBUG trap, armed only
  # between showing a prompt and the next command. It misses lines that are
  # only a subshell, like "(exit 3)".
  __seam_debug() {
    [[ $__seam_armed == 1 ]] || return 0
    [[ $BASH_COMMAND == __seam_* ]] && return 0
    __seam_armed=0
    __seam_start "$BASH_COMMAND"
    __seam_running=1
  }
  trap '__seam_debug' DEBUG
fi

__seam_precmd() {
  local code=$?
  if [[ $__seam_running == 1 ]]; then
    __seam_running=0
    __seam_line
    printf 'E\\t%s\\t%s\\n' "$REPLY" "$code" >> "$SEAM_EVENTS" 2>/dev/null
  fi
  return $code
}

__seam_prompt_done() { __seam_armed=1; }

# __seam_precmd runs first to see the exit status; __seam_prompt_done last,
# so the user's own PROMPT_COMMAND does not count as a command.
if [[ "$(declare -p PROMPT_COMMAND 2>/dev/null)" == "declare -a"* ]]; then
  PROMPT_COMMAND=(__seam_precmd "\${PROMPT_COMMAND[@]}" __seam_prompt_done)
else
  PROMPT_COMMAND="__seam_precmd\${PROMPT_COMMAND:+; $PROMPT_COMMAND}; __seam_prompt_done"
fi
`

export const SHELL_INTEGRATION_FILES: Record<string, string> = {
  'zsh/.zshenv': ZSHENV,
  'zsh/.zprofile': ZPROFILE,
  'zsh/.zshrc': ZSHRC,
  'zsh/seam-integration.zsh': ZSH_INTEGRATION,
  'bash/seam-init.bash': BASH_INIT,
  'bash/seam-integration.bash': BASH_INTEGRATION
}

/** Write the integration files (overwriting older versions). Returns their root. */
export function installShellIntegration(dir: string): string {
  for (const [rel, content] of Object.entries(SHELL_INTEGRATION_FILES)) {
    const file = join(dir, rel)
    mkdirSync(join(file, '..'), { recursive: true })
    writeFileSync(file, content)
  }
  return dir
}

export interface ShellLaunch {
  command: string[]
  env: Record<string, string>
  /** False for shells Seam cannot integrate with (they still work, unreported). */
  integrated: boolean
}

/**
 * How to start the user's shell with integration loaded. zsh and bash are
 * supported; anything else starts as a plain login shell.
 */
export function shellLaunch(o: {
  shell: string
  integrationDir: string
  eventsFile: string
  tmuxBinary: string
  homeDir: string
  userZdotdir?: string | undefined
}): ShellLaunch {
  const name = basename(o.shell)
  const env = { SEAM_EVENTS: o.eventsFile, SEAM_TMUX_BIN: o.tmuxBinary }
  if (name === 'zsh') {
    return {
      command: [o.shell, '-l'],
      env: { ...env, ZDOTDIR: join(o.integrationDir, 'zsh'), SEAM_USER_ZDOTDIR: o.userZdotdir || o.homeDir },
      integrated: true
    }
  }
  if (name === 'bash') {
    return { command: [o.shell, '--init-file', join(o.integrationDir, 'bash', 'seam-init.bash')], env, integrated: true }
  }
  return { command: [o.shell, '-l'], env, integrated: false }
}
