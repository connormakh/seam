import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * The `seam` MCP server: the process Claude Code spawns from --mcp-config.
 *
 * It is deliberately dumb. It holds no state, knows no policy, and does not
 * even know which tools exist: it asks the control socket for the tool list
 * and forwards every call there, carrying the token Seam put in its
 * environment. Everything that decides anything stays in the app, where it
 * can be tested and where a running Claude cannot reach it.
 *
 * It is written out rather than bundled because Claude spawns it, not
 * Electron: a plain file with no imports beyond node's own always resolves,
 * whatever the app was packaged with. Shell integration is installed the
 * same way, for the same reason.
 */
const SERVER = `#!/usr/bin/env node
// Generated by Seam. Edits are overwritten on launch.
import { connect } from 'node:net'

const SOCKET = process.env.SEAM_SOCKET
const TOKEN = process.env.SEAM_SESSION_TOKEN
const PROTOCOL = '2025-06-18'

// One connection per call. A tool call is never hot, and a fresh socket
// means no reconnect logic when Seam restarts underneath us.
function call(method, params) {
  return new Promise((resolve, reject) => {
    if (!SOCKET || !TOKEN) return reject(new Error('Seam is not running'))
    const socket = connect(SOCKET)
    let buffer = ''
    const fail = (e) => {
      socket.destroy()
      reject(e instanceof Error ? e : new Error(String(e)))
    }
    socket.setEncoding('utf8')
    socket.on('error', fail)
    socket.on('close', () => reject(new Error('Seam closed the connection')))
    socket.on('connect', () => {
      socket.write(JSON.stringify({ id: 1, token: TOKEN, method, params: params || {} }) + '\\n')
    })
    socket.on('data', (chunk) => {
      buffer += chunk
      const cut = buffer.indexOf('\\n')
      if (cut === -1) return
      socket.destroy()
      let reply
      try {
        reply = JSON.parse(buffer.slice(0, cut))
      } catch {
        return reject(new Error('Seam sent a reply that could not be read'))
      }
      if (reply && reply.ok) resolve(reply.result)
      else reject(new Error((reply && reply.error) || 'Seam refused the request'))
    })
  })
}

function send(message) {
  process.stdout.write(JSON.stringify(message) + '\\n')
}

function reply(id, result) {
  send({ jsonrpc: '2.0', id, result })
}

function replyError(id, code, message) {
  send({ jsonrpc: '2.0', id, error: { code, message } })
}

async function handle(request) {
  const { id, method, params } = request
  // A notification has no id and takes no reply.
  if (id === undefined || id === null) return

  if (method === 'initialize') {
    const asked = params && params.protocolVersion
    reply(id, {
      protocolVersion: typeof asked === 'string' ? asked : PROTOCOL,
      capabilities: { tools: {} },
      serverInfo: { name: 'seam', version: '0.0.0' }
    })
    return
  }
  if (method === 'ping') return reply(id, {})

  try {
    if (method === 'tools/list') return reply(id, { tools: await call('tools/list', {}) })
    if (method === 'tools/call') {
      const result = await call('tools/call', { name: params.name, arguments: params.arguments || {} })
      return reply(id, { content: [{ type: 'text', text: result.text }], isError: !!result.isError })
    }
    replyError(id, -32601, 'unknown method: ' + method)
  } catch (e) {
    // A failed tool call is a result Claude can read and react to, not a
    // protocol error; a protocol error would just end the conversation.
    if (method === 'tools/call') {
      return reply(id, { content: [{ type: 'text', text: String(e.message || e) }], isError: true })
    }
    replyError(id, -32603, String(e.message || e))
  }
}

let buffer = ''
process.stdin.setEncoding('utf8')
process.stdin.on('data', (chunk) => {
  buffer += chunk
  let cut = buffer.indexOf('\\n')
  while (cut !== -1) {
    const line = buffer.slice(0, cut)
    buffer = buffer.slice(cut + 1)
    if (line.trim()) {
      try {
        handle(JSON.parse(line))
      } catch {
        replyError(null, -32700, 'could not parse')
      }
    }
    cut = buffer.indexOf('\\n')
  }
})
process.stdin.on('end', () => process.exit(0))
`

/** Write the MCP server where Claude can run it. Returns its path. */
export function installMcpServer(dir: string): string {
  mkdirSync(dir, { recursive: true, mode: 0o700 })
  const file = join(dir, 'seam-mcp.mjs')
  writeFileSync(file, SERVER, { mode: 0o700 })
  return file
}

/**
 * The --mcp-config Claude is started with. Written per session, because the
 * token in it is the session's own.
 *
 * `node` comes from Seam's own process rather than PATH: a Finder-launched
 * app has barely any PATH, and this has to work whether or not the user has
 * node installed at all.
 */
export function writeMcpConfig(o: { dir: string; sessionId: string; serverPath: string; nodePath: string }): string {
  mkdirSync(o.dir, { recursive: true, mode: 0o700 })
  const file = join(o.dir, `${o.sessionId}.mcp.json`)
  const config = {
    mcpServers: {
      seam: {
        type: 'stdio',
        command: o.nodePath,
        args: [o.serverPath],
        // ELECTRON_RUN_AS_NODE makes Electron's binary behave as plain node,
        // which is what it has to be here.
        env: { ELECTRON_RUN_AS_NODE: '1' }
      }
    }
  }
  writeFileSync(file, `${JSON.stringify(config, null, 2)}\n`, { mode: 0o600 })
  return file
}
