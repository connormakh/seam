/**
 * Config for Seam's private tmux server. The user never drives this tmux
 * directly: Seam is the UI, tmux is only there to keep processes alive and
 * hold scrollback, so it should be invisible.
 */
export const TMUX_CONFIG = `# Generated by Seam. Edits are overwritten on launch.

# No prefix key: every keystroke goes to the program in the pane.
set -g prefix None
set -g prefix2 None

# No status line or titles; Seam draws its own chrome.
set -g status off
set -g set-titles off

# Wheel scrolling enters tmux history. Revisit with xterm.js selection in M2.
set -g mouse on

# Long history: shell-to-Claude reads command output out of it.
set -g history-limit 50000

set -s escape-time 0
set -g focus-events on
set -g default-terminal "xterm-256color"
set -as terminal-features ",xterm-256color:RGB"
set -g allow-passthrough on
set -s set-clipboard on

# The most recently active tab decides the size when several are attached.
set -g window-size latest

# Keep sessions running with no client attached; that is the point.
set -g destroy-unattached off
`
